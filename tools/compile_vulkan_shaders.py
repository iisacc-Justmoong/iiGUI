"""Rebuild checked-in SPIR-V from the GLSL sources with Khronos glslang."""
from pathlib import Path
import argparse
import hashlib
import struct
import subprocess

root=Path(__file__).resolve().parents[1]
parser=argparse.ArgumentParser()
parser.add_argument('glslang',help='Path to the official glslang/glslangValidator executable')
args=parser.parse_args()
build=root/'build/shaders'
build.mkdir(parents=True,exist_ok=True)
lines=['// Generated by tools/compile_vulkan_shaders.py; edit src/shaders instead.','#pragma once','#include <cstdint>','namespace ii::gui::detail {']
for name in ('panels.vert','panels.frag','text.vert','text.frag','effect.frag'):
    source=root/'src/shaders'/name
    target=build/(name+'.spv')
    subprocess.run([args.glslang,'-V','--target-env','vulkan1.1','-o',str(target),str(source)],check=True)
    data=target.read_bytes()
    words=struct.unpack('<'+'I'*(len(data)//4),data)
    lines += ['// '+name+' SHA256 '+hashlib.sha256(source.read_bytes()).hexdigest(),
              'inline constexpr std::uint32_t '+name.replace('.','_')+'[]{']
    lines += ['    '+','.join(f'0x{w:08x}u' for w in words[i:i+8])+',' for i in range(0,len(words),8)]
    lines += ['};']
lines += ['} // namespace ii::gui::detail','']
(root/'src/iiGUI/VulkanShaders.h').write_text('\n'.join(lines))
